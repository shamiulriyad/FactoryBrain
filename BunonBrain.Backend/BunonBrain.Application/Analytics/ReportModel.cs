using System.Globalization;
using System.Text;
using BunonBrain.Application.Workers;

namespace BunonBrain.Application.Analytics;

public static class ReportTypes
{
    public const string DailyOperations = "daily-operations";
    public const string WeeklyOperations = "weekly-operations";
    public const string MonthlyOperations = "monthly-operations";
    public const string Production = "production";
    public const string Machines = "machines";
    public const string Attendance = "attendance";
    public const string Overtime = "overtime";
    public const string DeviceHealth = "device-health";
    public const string AiActivity = "ai-activity";

    public static readonly IReadOnlyList<string> All =
        new[] { DailyOperations, WeeklyOperations, MonthlyOperations, Production, Machines, Attendance, Overtime, DeviceHealth, AiActivity };

    public static string? Parse(string? v) => All.FirstOrDefault(t => string.Equals(t, v?.Trim(), StringComparison.OrdinalIgnoreCase));

    public static string Title(string t) => t switch
    {
        DailyOperations => "Daily factory operations report",
        WeeklyOperations => "Weekly operations report",
        MonthlyOperations => "Monthly operations report",
        Production => "Production report",
        Machines => "Machine performance report",
        Attendance => "Attendance report",
        Overtime => "Overtime report",
        DeviceHealth => "Device health report",
        _ => "AI activity observation report",
    };

    /// <summary>The operations reports' period ending on <paramref name="end"/>: 1, 7 or 30 days.</summary>
    public static int? FixedDays(string t) => t switch { DailyOperations => 1, WeeklyOperations => 7, MonthlyOperations => 30, _ => null };
}

public sealed record ReportTable(string Title, IReadOnlyList<string> Columns, IReadOnlyList<IReadOnlyList<object?>> Rows, string? Note = null);

public sealed record ReportSection(string Title, IReadOnlyList<Kpi> Kpis, IReadOnlyList<ReportTable> Tables, string? Note = null);

public sealed record ReportFilter(string Name, string Value);

/// <summary>A generated report: what it covers, for whom, from which data, with which caveats.</summary>
public sealed record ReportDocument(
    string Type,
    string Title,
    DateTimeOffset GeneratedAt,
    string GeneratedBy,
    string Scope,
    DateOnly From,
    DateOnly To,
    string TimeZone,
    string Source,
    IReadOnlyList<ReportFilter> Filters,
    IReadOnlyList<ReportSection> Sections,
    IReadOnlyList<string> Warnings,
    IReadOnlyList<MetricDefinition> Definitions);

/// <summary>CSV export of a report: a header block, then every section's KPIs and tables, then the metric definitions.</summary>
public static class ReportCsv
{
    private static string Cell(object? v) => v switch
    {
        null => "",
        double d => double.IsFinite(d) ? d.ToString("0.##", CultureInfo.InvariantCulture) : "",
        float f => ((double)f).ToString("0.##", CultureInfo.InvariantCulture),
        int or long or short or decimal => Convert.ToString(v, CultureInfo.InvariantCulture)!,
        DateTimeOffset t => t.ToString("yyyy-MM-dd HH:mm:ss'Z'", CultureInfo.InvariantCulture),
        DateOnly d => d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        bool b => b ? "yes" : "no",
        // Text is escaped (quotes, formula injection guard).
        _ => Csv.Escape(Convert.ToString(v, CultureInfo.InvariantCulture)),
    };

    private static void Row(StringBuilder sb, IEnumerable<object?> cells) => sb.Append(string.Join(",", cells.Select(Cell))).Append("\r\n");

    public static string Write(ReportDocument r)
    {
        var sb = new StringBuilder();
        Row(sb, new object?[] { r.Title });
        Row(sb, new object?[] { "Generated at (UTC)", r.GeneratedAt });
        Row(sb, new object?[] { "Generated by", r.GeneratedBy });
        Row(sb, new object?[] { "Scope", r.Scope });
        Row(sb, new object?[] { "Period", $"{r.From:yyyy-MM-dd} to {r.To:yyyy-MM-dd} ({r.TimeZone})" });
        Row(sb, new object?[] { "Data", r.Source == "SIMULATED" ? "SIMULATED data - not real production or machines" : "REAL data" });
        foreach (var f in r.Filters) Row(sb, new object?[] { $"Filter: {f.Name}", f.Value });
        foreach (var w in r.Warnings) Row(sb, new object?[] { "Warning", w });
        foreach (var s in r.Sections)
        {
            sb.Append("\r\n");
            Row(sb, new object?[] { s.Title });
            if (s.Note is not null) Row(sb, new object?[] { "Note", s.Note });
            if (s.Kpis.Count > 0)
            {
                Row(sb, new object?[] { "metric", "value", "unit", "numerator", "denominator", "kind", "availability", "note" });
                foreach (var k in s.Kpis) Row(sb, new object?[] { k.Label, k.Value, k.Unit, k.Numerator, k.Denominator, k.Kind, k.Availability, k.Note });
            }
            foreach (var t in s.Tables)
            {
                sb.Append("\r\n");
                Row(sb, new object?[] { t.Title });
                if (t.Note is not null) Row(sb, new object?[] { "Note", t.Note });
                Row(sb, t.Columns);
                foreach (var row in t.Rows) Row(sb, row);
            }
        }
        sb.Append("\r\n");
        Row(sb, new object?[] { "Metric definitions" });
        Row(sb, new object?[] { "id", "name", "kind", "unit", "formula", "window", "includes", "excludes", "denominator", "missing data", "sources" });
        foreach (var d in r.Definitions)
            Row(sb, new object?[] { d.Id, d.Name, d.Kind, d.Unit, d.Formula, d.Window, d.Includes, d.Excludes, d.Denominator, d.MissingData, string.Join("; ", d.Sources) });
        return sb.ToString();
    }

    public static string FileName(ReportDocument r, string extension) =>
        $"bunonbrain-{r.Type}-{r.From:yyyyMMdd}-{r.To:yyyyMMdd}{(r.Source == "SIMULATED" ? "-SIMULATED" : "")}.{extension}";
}
