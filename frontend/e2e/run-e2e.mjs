// End-to-end harness: disposable PostgreSQL + pgvector, the real .NET API,
// a fake OpenAI-compatible model, the production Next.js build, then the
// authenticated RAG eval (scripts/test-rag.mjs) and the Playwright suite.
//
//   npm run e2e            (from frontend/)
//
// Isolation rules this script enforces:
//   - The database is a fresh `pgvector/pgvector:pg16` container with random,
//     test-only credentials, bound to 127.0.0.1, removed at the end.
//   - The API runs in ASPNETCORE_ENVIRONMENT=IntegrationTesting: it ignores
//     the repo-root .env and refuses any non-loopback database.
//   - The Next.js build/start run with FACTORYBRAIN_SKIP_ROOT_ENV=1, so the
//     repo-root .env is not loaded there either.
//   - The API gets HTTP(S)_PROXY pointing at a closed local port (NO_PROXY
//     for 127.0.0.1/localhost): any accidental call to a real provider fails
//     instead of leaving the machine. The only "LLM" is the local fake.
//
// Exit code: 0 when every stage passes, 1 otherwise.

import { spawn, execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash, randomBytes } from "node:crypto";
import { createServer } from "node:net";
import http from "node:http";
import { promises as fs, createWriteStream } from "node:fs";
import path from "node:path";
import url from "node:url";

const run = promisify(execFile);
const here = path.dirname(url.fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "..");
const repo = path.resolve(frontend, "..");
const apiProject = path.join(repo, "FactoryBrain.Backend", "FactoryBrain.Api");
// E2E_API_DLL: run an API build from another folder (e.g. when a developer's
// running API locks bin/Debug and the code under test was built elsewhere).
const apiDll = process.env.E2E_API_DLL || path.join(apiProject, "bin", "Debug", "net9.0", "FactoryBrain.Api.dll");
const artifacts = path.join(here, ".artifacts");

const secret = (n = 24) => randomBytes(n).toString("base64url");
const log = (...a) => console.log("[e2e]", ...a);

async function freePort() {
  return new Promise((resolve, reject) => {
    const s = createServer();
    s.unref();
    s.on("error", reject);
    s.listen(0, "127.0.0.1", () => {
      const { port } = s.address();
      s.close(() => resolve(port));
    });
  });
}

async function waitFor(label, fn, timeoutMs = 120_000, intervalMs = 500) {
  const deadline = Date.now() + timeoutMs;
  let last;
  while (Date.now() < deadline) {
    try {
      if (await fn()) return;
    } catch (e) {
      last = e;
    }
    await new Promise((r) => setTimeout(r, intervalMs));
  }
  throw new Error(`timed out waiting for ${label}${last ? `: ${last.message}` : ""}`);
}

function startProcess(label, command, args, options) {
  const out = createWriteStream(path.join(artifacts, `${label}.log`));
  const child = spawn(command, args, { ...options, stdio: ["ignore", "pipe", "pipe"] });
  child.stdout.pipe(out);
  child.stderr.pipe(out);
  child.on("exit", (code) => log(`${label} exited (${code})`));
  return child;
}

async function runStep(label, command, args, options) {
  return new Promise((resolve) => {
    const child = spawn(command, args, { ...options, stdio: "inherit" });
    child.on("exit", (code) => {
      log(`${label}: exit ${code}`);
      resolve(code ?? 1);
    });
  });
}

