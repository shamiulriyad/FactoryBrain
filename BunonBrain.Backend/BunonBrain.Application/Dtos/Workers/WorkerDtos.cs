// ─── Workers ───────────────────────────────────────────────────────────────

/// <summary>
/// A worker, as much of it as the caller may see. Three tiers:
/// <list type="bullet">
///   <item><b>Basic</b> (anyone who can see the worker): Worker ID, name,
///   placement, designation, status.</item>
///   <item><b>Employment</b> (<c>workers.details.view</c>, <c>workers.manage</c>,
///   or the worker themself): employee number, joining date, grade, status
///   reason, whether a login account is linked.</item>
///   <item><b>Personal</b> (<c>workers.manage</c> or the worker themself):
///   phone, email, gender, date of birth, address, emergency contact.</item>
/// </list>
/// Fields outside the caller's tier are null (and so omitted from the JSON).
/// </summary>
public sealed record WorkerDto(
    Guid Id,
    string WorkerCode,
    Guid FactoryId,
    string FullName,
    bool HasPhoto,
    string Status,
    bool IsActive,
    string? Designation,
    OrgRef? Department,
    OrgRef? Floor,
    WorkerLineRef? Line,
    string? LineId,
    string? Workstation,
    // Employment tier
    string? EmploymentType,
    string? EmployeeCode,
    DateOnly? JoinedOn,
    string? Grade,
    string? StatusReason,
    DateTimeOffset? StatusChangedAt,
    bool? HasAccount,
    DateTimeOffset? CreatedAt,
    DateTimeOffset? UpdatedAt,
    // Personal tier
    string? Phone,
    string? Email,
    string? Gender,
    DateOnly? DateOfBirth,
    string? PresentAddress,
    string? EmergencyContactName,
    string? EmergencyContactPhone,
    string? EmergencyContactRelation,
    Guid? UserId,
    // Which tiers this response carries: <c>basic</c>, <c>employment</c> or <c>full</c>.
    string Detail);

/// <summary>
/// GET /api/workers query. <c>sort</c>: workerId | name | joined | status |
/// department | designation | created, prefix "-" for descending.
/// </summary>
public sealed record WorkerListQuery(
    string? Search = null, Guid? FactoryId = null, Guid? DepartmentId = null, Guid? FloorId = null, string? LineId = null,
    string? Status = null, string? Designation = null, string? EmploymentType = null,
    string? Sort = null, int Page = 1, int PageSize = 25);

/// <summary>POST /api/workers. The Worker ID is generated by the server.</summary>
public sealed record CreateWorkerRequest(
    Guid FactoryId,
    string FullName,
    string? Phone,
    DateOnly? JoinedOn,
    Guid? DepartmentId,
    string? Designation,
    string? EmploymentType = null,
    string? EmployeeCode = null,
    string? Gender = null,
    DateOnly? DateOfBirth = null,
    string? Email = null,
    string? PresentAddress = null,
    string? EmergencyContactName = null,
    string? EmergencyContactPhone = null,
    string? EmergencyContactRelation = null,
    Guid? FloorId = null,
    string? LineId = null,
    string? Workstation = null,
    string? Grade = null);

/// <summary>
/// PUT /api/workers/{id}: the complete editable record. The factory and the
/// Worker ID can't be changed; the status is changed with PATCH …/status.
/// </summary>
public sealed record UpdateWorkerRequest(
    string FullName,
    string? Phone,
    DateOnly? JoinedOn,
    Guid? DepartmentId,
    string? Designation,
    string? EmploymentType = null,
    string? EmployeeCode = null,
    string? Gender = null,
    DateOnly? DateOfBirth = null,
    string? Email = null,
    string? PresentAddress = null,
    string? EmergencyContactName = null,
    string? EmergencyContactPhone = null,
    string? EmergencyContactRelation = null,
    Guid? FloorId = null,
    string? LineId = null,
    string? Grade = null);

/// <summary>PATCH /api/workers/{id}/status.</summary>
public sealed record ChangeWorkerStatusRequest(string Status, string? Reason = null, DateOnly? EffectiveOn = null);

/// <summary>PUT /api/workers/{id}/workstation.</summary>
public sealed record AssignWorkstationRequest(string? LineId, string? Workstation);

/// <summary>PUT /api/workers/{id}/account: link (or with null, unlink) an existing login account.</summary>
public sealed record LinkWorkerAccountRequest(Guid? UserId);

/// <summary>POST /api/workers/{id}/account: create a login for the worker (Worker role, own records only) and link it.</summary>
public sealed record CreateWorkerAccountRequest(string Email, string TemporaryPassword);

