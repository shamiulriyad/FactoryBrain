using BunonBrain.Application.Access;

namespace BunonBrain.Application.Dtos.Workers;

// ─── Organisation units ────────────────────────────────────────────────────

/// <summary>A department or production floor of a factory.</summary>
public sealed record OrgUnitDto(
    Guid Id, Guid FactoryId, string Code, string Name, bool IsActive, int WorkerCount,
    DateTimeOffset CreatedAt, DateTimeOffset UpdatedAt);

public sealed record CreateOrgUnitRequest(string Code, string Name);

