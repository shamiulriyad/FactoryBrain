"use client";

import { useMemo, useState } from "react";
import { Gauge, RefreshCw, Search, StepForward } from "lucide-react";
import { PageHeader } from "@/components/ui/PageHeader";
import { Panel } from "@/components/ui/Panel";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { Callout } from "@/components/ui/Callout";
import { FilterSelect } from "@/components/ui/Field";
import { StatCard } from "@/components/ui/StatCard";
import { EmptyState } from "@/components/ui/EmptyState";
import { SkeletonRows } from "@/components/ui/Status";
import { useToast } from "@/components/ui/Toast";
import { useResource, announceDataChanged } from "@/lib/useResource";
import { apiJson, errorMessage } from "@/lib/api";
import { canOperate, useAuthStore } from "@/lib/auth";
import { formatDateTime, formatRelative } from "@/lib/format";
import { useT } from "@/lib/useT";
import { cn } from "@/lib/cn";
import type { LatestReadings, SensorSnapshot, SensorStatus } from "@/services/contracts";

const PAGE_SIZE = 50;
const MACHINE_TONE: Record<string, "success" | "warning" | "danger" | "neutral"> = { healthy: "success", at_risk: "warning", down: "danger" };

export default function SensorsPage() {
  const { locale } = useT();
  const toast = useToast();
  const operator = canOperate(useAuthStore((s) => s.user));
  const status = useResource<SensorStatus>("/api/sensors/ingest", { pollMs: 10_000 });
  const snapshot = useResource<SensorSnapshot>("/api/sensors/snapshot", { pollMs: 10_000 });
  const latest = useResource<LatestReadings>("/api/sensors/latest", { pollMs: 15_000 });
  const [source, setSource] = useState("");
  const [query, setQuery] = useState("");
  const [visible, setVisible] = useState(PAGE_SIZE);
  const [advancing, setAdvancing] = useState(false);

  const readings = useMemo(() => {
    const q = query.trim().toLowerCase();
    return (latest.data?.readings ?? []).filter(
      (r) => (!source || r.source === source) && (!q || r.entityId.toLowerCase().includes(q) || r.metric.toLowerCase().includes(q))
    );
  }, [latest.data, source, query]);
  const sources = Array.from(new Set((latest.data?.readings ?? []).map((r) => r.source))).sort();

  async function advance() {
    if (advancing) return;
    setAdvancing(true);
    try {
      const next = await apiJson<SensorSnapshot>("/api/sensors/ingest", { method: "POST", body: {} });
      snapshot.setData(next);
      void status.reload();
      void latest.reload();
      announceDataChanged();
      toast.push({ title: "Simulation advanced", description: `Tick #${next.tick} · ${next.readings.length} readings stored.` });
    } catch (e) {
      toast.push({ tone: "error", title: "Could not advance the simulation", description: errorMessage(e) });
    } finally {
      setAdvancing(false);
    }
  }

  function reloadAll() {
    void status.reload();
    void snapshot.reload();
    void latest.reload();
  }

  const s = status.data;
  return (
    <div className="page" data-testid="sensors-page">
      <PageHeader
        eyebrow="Operations"
        title="Sensors"
        description="RFID, telemetry and energy readings the API has stored, with the current line and machine roll-up."
        meta={
          s ? (
            <span title={s.source} data-testid="sensors-source">
              <Badge tone={s.simulated ? "accent" : "success"} dot>{s.simulated ? "Simulated readings" : "Live gateway readings"}</Badge>
            </span>
          ) : null
        }
        actions={
          <>
            {operator && (
              <Button variant="secondary" size="sm" onClick={() => void advance()} disabled={advancing} title="Generate and store one simulated tick (Operator)">
                <StepForward size={13} /> {advancing ? "Advancing…" : "Advance simulation"}
              </Button>
            )}
            <Button variant="secondary" size="sm" onClick={reloadAll} disabled={latest.refreshing} aria-label="Refresh sensors">
              <RefreshCw size={13} className={cn(latest.refreshing && "animate-spin")} /> Refresh
            </Button>
          </>
        }
      />

      {s && (
        <Callout tone={s.simulated ? "demo" : "success"} className="mt-5" title={s.simulated ? "These readings are generated by the built-in simulator" : "Readings come from a floor gateway"}>
          {s.source} Gateways post batches to <span className="font-mono">POST /api/sensors/live</span> with an Operator account.
        </Callout>
      )}

      <section className="mt-5 grid grid-cols-2 lg:grid-cols-4 gap-3" aria-label="Sensor status">
        <StatCard label="Simulation tick" value={s ? `#${s.tick}` : "—"} loading={status.loading} error={status.error && !s ? "Unavailable" : null} icon={<Gauge size={15} />} />
        <StatCard label="Readings this tick" value={s ? `${s.readingsCount}` : "—"} loading={status.loading} error={status.error && !s ? "Unavailable" : null} />
        <StatCard label="Lines reporting" value={s ? `${s.linesCount}` : "—"} loading={status.loading} error={status.error && !s ? "Unavailable" : null} />
        <StatCard label="Machines reporting" value={s ? `${s.machinesCount}` : "—"} loading={status.loading} error={status.error && !s ? "Unavailable" : null} />
      </section>

      <div className="mt-4 grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Panel title="Lines" subtitle="Roll-up from the latest snapshot" flush>
          {snapshot.loading ? (
            <div className="p-4"><SkeletonRows rows={4} rowHeight="h-9" /></div>
          ) : (snapshot.data?.lines.length ?? 0) === 0 ? (
            <p className="p-5 text-caption text-fg-tertiary">{snapshot.error ? errorMessage(snapshot.error) : "No lines reporting."}</p>
          ) : (
            <div className="overflow-x-auto">
              <table className="data-table">
                <thead><tr><th>Line</th><th className="num">Efficiency</th><th className="num">Uptime</th><th className="num">Energy</th></tr></thead>
                <tbody>
                  {snapshot.data!.lines.map((l) => (
                    <tr key={l.id}>
                      <td className="font-mono text-fg-primary">{l.id}</td>
                      <td className="num">{Math.round(l.efficiency * 100)}%</td>
                      <td className="num">{Math.round(l.uptime * 100)}%</td>
                      <td className="num">{l.energyKwh.toFixed(1)} kWh</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Panel>
        <Panel title="Machines" subtitle="Vibration, temperature and duty cycle" flush>
          {snapshot.loading ? (
            <div className="p-4"><SkeletonRows rows={4} rowHeight="h-9" /></div>
          ) : (snapshot.data?.machines.length ?? 0) === 0 ? (
            <p className="p-5 text-caption text-fg-tertiary">{snapshot.error ? errorMessage(snapshot.error) : "No machines reporting."}</p>
          ) : (
            <div className="overflow-x-auto">
              <table className="data-table">
                <thead><tr><th>Machine</th><th>Status</th><th className="num">Vibration</th><th className="num">Temp</th><th className="num">Duty</th></tr></thead>
                <tbody>
                  {snapshot.data!.machines.map((m) => (
                    <tr key={m.id}>
                      <td className="font-mono text-fg-primary">{m.id}</td>
                      <td><Badge tone={MACHINE_TONE[m.status] ?? "neutral"} dot>{m.status.replace("_", " ")}</Badge></td>
                      <td className="num">{m.vibration.toFixed(1)} mm/s</td>
                      <td className="num">{m.temperature.toFixed(1)} °C</td>
                      <td className="num">{Math.round(m.dutyCycle * 100)}%</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Panel>
      </div>

      <Panel
        className="mt-4"
        flush
        title="Latest stored readings"
        subtitle={latest.data ? `${readings.length} of ${latest.data.count} shown` : undefined}
        right={
          <>
            <div className="relative">
              <Search size={14} className="absolute left-2.5 top-1/2 -translate-y-1/2 text-fg-tertiary" aria-hidden />
              <input
                type="search"
                value={query}
                onChange={(e) => { setQuery(e.target.value); setVisible(PAGE_SIZE); }}
                placeholder="Entity or metric"
                aria-label="Filter readings by entity or metric"
                className="control !h-8 !pl-8 !w-48 !text-caption"
              />
            </div>
            <FilterSelect label="Source" value={source} onChange={(v) => { setSource(v); setVisible(PAGE_SIZE); }}>
              <option value="">All</option>
              {sources.map((s) => <option key={s} value={s}>{s}</option>)}
            </FilterSelect>
          </>
        }
      >
        {latest.error && !latest.data ? (
          <div className="p-4"><Callout tone="danger" title="Could not load readings">{errorMessage(latest.error)}</Callout></div>
        ) : latest.loading ? (
          <div className="p-4"><SkeletonRows rows={6} rowHeight="h-9" /></div>
        ) : readings.length === 0 ? (
          <EmptyState icon={<Gauge size={22} />} title="No readings match." body={latest.data?.count ? "Change the filter." : "Advance the simulation or connect a gateway."} />
        ) : (
          <div className="overflow-x-auto max-h-[520px]">
            <table className="data-table" data-testid="sensor-readings">
              <thead><tr><th>Time</th><th>Source</th><th>Entity</th><th>Metric</th><th className="num">Value</th><th className="num">Tick</th></tr></thead>
              <tbody>
                {readings.slice(0, visible).map((r) => (
                  <tr key={r.id}>
                    <td className="whitespace-nowrap" title={formatDateTime(r.ts, locale)}>{formatRelative(r.ts, locale)}</td>
                    <td><Badge>{r.source}</Badge></td>
                    <td className="font-mono text-fg-primary">{r.entityId}</td>
                    <td>{r.metric}</td>
                    <td className="num text-fg-primary">{Number.isInteger(r.value) ? r.value : r.value.toFixed(2)} <span className="text-fg-tertiary">{r.unit}</span></td>
                    <td className="num">{r.simTick}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
        {readings.length > visible && (
          <div className="p-3 flex justify-center border-t border-border-subtle">
            <Button variant="secondary" size="sm" onClick={() => setVisible((v) => v + PAGE_SIZE)}>Show more ({readings.length - visible})</Button>
          </div>
        )}
      </Panel>
    </div>
  );
}
