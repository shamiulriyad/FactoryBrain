// ─── Import / export ───────────────────────────────────────────────────────

public sealed record WorkerImportIssueDto(string Field, string Message);

public sealed record WorkerImportRowDto(
    int RowNumber, bool Valid,
    string? FullName, string? EmployeeCode, string? Phone, DateOnly? JoinedOn,
    string? Department, string? Designation, string? EmploymentType, string? Floor, string? Line,
    IReadOnlyList<WorkerImportIssueDto> Errors,
