export type AlertAction = "acknowledge" | "escalate" | "resolve" | "dismiss";

const ACTION_TITLE: Record<AlertAction, string> = {
  acknowledge: "Acknowledge alert",
  escalate: "Escalate alert",
  resolve: "Resolve alert",
  dismiss: "Dismiss alert"
};

/**
 * The confirmation dialog for one alert action. The server checks the state,
 * the permission and (via expectedVersion) that nobody changed it meanwhile.
 */
export function AlertActionDialog({ alert, action, onClose, onDone }: {
  alert: MonitoringAlert | null;
  action: AlertAction | null;
  onClose: () => void;
  onDone: (d: MonitoringAlertDetail) => void;
}) {
  const toast = useToast();
  const [note, setNote] = useState("");
  const [role, setRole] = useState("FactoryManager");
  const [code, setCode] = useState("ISSUE_FIXED");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const open = !!alert && !!action;

  function close() {
    setNote("");
    setError(null);
    onClose();
  }

  async function submit() {
    if (!alert || !action) return;
    setBusy(true);
    setError(null);
    const body =
      action === "acknowledge" ? { note: note || null, expectedVersion: alert.version }
      : action === "escalate" ? { toRole: role, reason: note, expectedVersion: alert.version }
      : action === "resolve" ? { resolutionCode: code, note, expectedVersion: alert.version }
      : { reason: note, expectedVersion: alert.version };
    try {
      const d = await apiJson<MonitoringAlertDetail>(`/api/monitoring/alerts/${alert.id}/${action}`, { method: "POST", body });
      toast.push({ tone: "success", title: `${alert.code}: ${ALERT_STATUS_LABEL[d.alert.status] ?? d.alert.status}` });
      setNote("");
      onDone(d);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setBusy(false);
    }
  }

  const needsNote = action === "escalate" || action === "resolve" || action === "dismiss";
  const noteOk = !needsNote || (action === "dismiss" ? note.trim().length >= 5 : note.trim().length > 0);
  return (
    <Modal open={open} onClose={close} locked={busy} title={action ? ACTION_TITLE[action] : ""}
      description={alert ? `${alert.code} · ${alert.title}` : undefined} testId="alert-action-dialog"
      footer={
        <>
          <Button variant="ghost" onClick={close} disabled={busy}>Cancel</Button>
          <Button variant={action === "dismiss" ? "danger" : "primary"} onClick={() => void submit()} disabled={busy || !noteOk} data-testid="alert-action-confirm">
            {busy ? "Saving…" : action ? ACTION_TITLE[action].replace(" alert", "") : ""}
          </Button>
        </>
      }>
      <div className="space-y-4">
        {alert?.isSimulated && <Callout tone="warning">This alert comes from SIMULATED data. Acting on it is recorded like any other action.</Callout>}
        {action === "escalate" && (
          <Field label="Escalate to">
            {(ids) => (
              <Select id={ids.id} value={role} onChange={(e) => setRole(e.target.value)} data-testid="escalate-role">
                {ESCALATION_TARGETS.map((t) => <option key={t.id} value={t.id}>{t.label}</option>)}
              </Select>
            )}
          </Field>
        )}
        {action === "resolve" && (
          <Field label="Resolution">
            {(ids) => (
              <Select id={ids.id} value={code} onChange={(e) => setCode(e.target.value)} data-testid="resolve-code">
                {Object.entries(RESOLUTION_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
              </Select>
            )}
          </Field>
        )}
        <Field label={action === "acknowledge" ? "Note (optional)" : action === "escalate" ? "Why escalate?" : action === "resolve" ? "What was found and done?" : "Why dismiss it? (at least 5 characters)"}>
          {(ids) => <TextArea id={ids.id} rows={3} maxLength={1000} value={note} onChange={(e) => setNote(e.target.value)} data-testid="alert-action-note" />}
        </Field>
        {action === "dismiss" && <p className="text-caption text-fg-tertiary">Dismissing closes the alert without action. The reason is kept in its history and the audit log.</p>}
        <p className="text-caption text-fg-tertiary flex items-center gap-1.5"><ShieldCheck size={12} aria-hidden /> Alerts never change pay, attendance or discipline by themselves.</p>
        {error && <Callout tone="danger">{error}</Callout>}
      </div>
    </Modal>
  );
}

/** The action buttons an alert currently allows this user. */
export function AlertActionButtons({ a, onAction, size = "sm" }: { a: MonitoringAlert; onAction: (action: AlertAction) => void; size?: "sm" | "md" }) {
  const any = a.can.acknowledge || a.can.escalate || a.can.resolve || a.can.dismiss;
  if (!any) return null;
  return (
    <div className="flex flex-wrap gap-2" data-testid="alert-actions">
      {a.can.acknowledge && <Button size={size} variant="primary" onClick={() => onAction("acknowledge")} data-testid="alert-acknowledge">Acknowledge</Button>}
      {a.can.resolve && <Button size={size} variant="primary" onClick={() => onAction("resolve")} data-testid="alert-resolve">Resolve</Button>}
      {a.can.escalate && <Button size={size} variant="secondary" onClick={() => onAction("escalate")} data-testid="alert-escalate">Escalate</Button>}
      {a.can.dismiss && <Button size={size} variant="ghost" onClick={() => onAction("dismiss")} data-testid="alert-dismiss">Dismiss</Button>}
    </div>
  );
}

/** Merge pushed events into a list: newest first, no duplicates, capped. */
export function mergeEvents(list: MonitoringEvent[], incoming: MonitoringEvent, cap = 100): MonitoringEvent[] {
  if (list.some((e) => e.id === incoming.id)) return list;
  return [incoming, ...list].sort((a, b) => b.occurredAt.localeCompare(a.occurredAt)).slice(0, cap);
}
