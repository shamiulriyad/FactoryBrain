"use client";

import Link from "next/link";
import { useState } from "react";
import { Panel } from "@/components/ui/Panel";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { Callout } from "@/components/ui/Callout";
import { Select } from "@/components/ui/Field";
import { Input } from "@/components/ui/Input";
import { StatCard } from "@/components/ui/StatCard";
import { useToast } from "@/components/ui/Toast";
import { DataTable } from "@/components/analytics/shared";
import { DOCS, DocRiskBadge, DocsPage, Loaded, fmtDate, type DocScope } from "@/components/documents/shared";
import { useResource } from "@/lib/useResource";
import { errorMessage } from "@/lib/api";
import {
  APPROVAL_TEXT, docsApi, type ApprovalLevel, type DocType, type DocUsage, type ScheduleFrequency, type ScheduleRun, type ScheduleScope, type ScheduleStatus
} from "@/lib/documents";

const FREQ_TEXT: Record<ScheduleFrequency, string> = { DAILY: "Daily (yesterday)", WEEKLY: "Weekly (last full week)", MONTHLY: "Monthly (last month)" };
const DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const RUN_TONE: Record<ScheduleRun["status"], "success" | "info" | "neutral" | "danger"> = { CREATED: "success", EXISTS: "info", NO_DATA: "neutral", FAILED: "danger" };
const RUN_TEXT: Record<ScheduleRun["status"], string> = { CREATED: "Generated", EXISTS: "Already existed", NO_DATA: "No records yet", FAILED: "Failed" };

export default function Page() {
  return (
    <DocsPage title="Document settings" testId="documents-settings"
      description="Per document type: how it is approved, whether a draft is generated automatically from records (daily, weekly or monthly, for the factory or each line), whether its absence is reported, and how long a decision may take. High-risk types always need an approver.">
      {(scope) => <Settings scope={scope} />}
    </DocsPage>
  );
}

function Settings({ scope }: { scope: DocScope }) {
  const { catalog, factoryId } = scope;
  const usage = useResource<DocUsage>(catalog.can.control ? docsApi.usage(factoryId) : null);
  const runs = useResource<ScheduleStatus>(catalog.can.control || catalog.can.monitor ? docsApi.scheduleRuns(factoryId) : null);
  if (!catalog.can.control) return <Callout tone="info">Document settings are managed by the document controller and factory administrators.</Callout>;
  return (
    <div className="space-y-4">
      <Panel title="Scheduled generation" subtitle="Drafts are generated only for complete periods and only when the source records exist; each period is generated once per scope. Nothing is ever submitted or approved automatically.">
        <Loaded res={runs}>
          {(st) => (
            <div className="space-y-3">
              {st.automationEnabled
                ? <Callout tone="success" title="Automation is on">The server runs scheduled generation, missing-document and overdue checks every 30 minutes.</Callout>
                : <Callout tone="warning" title="Automation is off on the server">The schedules below are saved but nothing runs until the administrator sets DOCUMENT_AUTOMATION_ENABLED=true and restarts the API. Documents can still be generated by hand.</Callout>}
              <DataTable testId="schedule-runs" empty="No scheduled runs in the last 30 days."
                columns={["Document type", "Period", "Scope", "Result", "Attempts", "Document / error", "Last attempt"]}
                rows={st.runs.map((r) => [
                  r.typeName, r.periodFrom === r.periodTo ? r.periodFrom : `${r.periodFrom} – ${r.periodTo}`, r.lineKey === "*" ? "Factory" : r.lineKey,
                  <Badge key="s" tone={RUN_TONE[r.status]}>{RUN_TEXT[r.status]}</Badge>, r.attempts,
                  r.documentId && r.documentReference
                    ? <Link key="d" href={`${DOCS}/${r.documentId}?factory=${factoryId}`} className="font-mono text-[12px] text-accent hover:underline">{r.documentReference}</Link>
                    : <span key="e" className="text-fg-secondary text-[12px]">{r.errorMessage ?? "—"}</span>,
                  fmtDate(r.lastAttemptAt)
                ])} />
            </div>
          )}
        </Loaded>
      </Panel>
      <Panel title="AI usage (30 days)" subtitle={catalog.ai.configured ? `Provider ${catalog.ai.provider} · model ${catalog.ai.model}. Keys stay on the server (Settings → AI).` : catalog.ai.reason ?? undefined}>
        <Loaded res={usage}>
          {(u) => (
            <div className="space-y-3">
              <div className="grid gap-3 grid-cols-2 sm:grid-cols-4">
                <StatCard label="Calls" value={u.calls} />
                <StatCard label="Failed" value={u.failures} tone={u.failures ? "warn" : "neutral"} />
                <StatCard label="Input tokens" value={u.inputTokens.toLocaleString()} />
                <StatCard label="Output tokens" value={u.outputTokens.toLocaleString()} />
              </div>
              <DataTable columns={["Purpose", "Calls", "Failed"]} rows={u.byPurpose.map((p) => [p.purpose, p.calls, p.failures])} empty="No AI calls yet: everything so far was handled by rules." />
            </div>
          )}
        </Loaded>
      </Panel>
      {catalog.categoryList.map((c) => (
        <Panel key={c.code} title={c.name} flush ariaLabel={c.name}>
          <div className="overflow-x-auto">
            <table className="data-table">
              <thead><tr><th>Document type</th><th>Risk</th><th>Approval</th><th>Generate on schedule</th><th>Expected daily</th><th>Decision within (h)</th><th /></tr></thead>
              <tbody>{catalog.types.filter((t) => t.category === c.code).map((t) => <Row key={t.code} t={t} factoryId={factoryId} onSaved={() => { scope.reloadCatalog(); void runs.reload(); }} />)}</tbody>
            </table>
          </div>
        </Panel>
      ))}
    </div>
  );
}

function Row({ t, factoryId, onSaved }: { t: DocType; factoryId: string; onSaved: () => void }) {
  const toast = useToast();
  const freqs = t.scheduleFrequencies ?? [];
  const [level, setLevel] = useState<ApprovalLevel>(t.approvalLevel);
  const [auto, setAuto] = useState(t.autoGenerate);
  const [freq, setFreq] = useState<ScheduleFrequency>(t.scheduleFrequency ?? "DAILY");
  const [scopeV, setScopeV] = useState<ScheduleScope>(t.scheduleScope ?? "FACTORY");
  const [week, setWeek] = useState(t.weekStartDay ?? 6);
  const [expected, setExpected] = useState(t.expectedDaily);
  const [due, setDue] = useState(String(t.decisionDueHours));
  const [busy, setBusy] = useState(false);
  const dirty = level !== t.approvalLevel || auto !== t.autoGenerate || expected !== t.expectedDaily || due !== String(t.decisionDueHours)
    || freq !== t.scheduleFrequency || scopeV !== t.scheduleScope || week !== t.weekStartDay;
  const schedulable = t.generated && freqs.length > 0;
  async function save() {
    setBusy(true);
    try {
      await docsApi.saveSettings(factoryId, t.code, {
        approvalLevel: level, autoGenerate: auto, expectedDaily: expected, decisionDueHours: Number(due) || 24,
        ...(schedulable ? { scheduleFrequency: freq, scheduleScope: scopeV, weekStartDay: week } : {})
      });
      toast.push({ title: `${t.name}: saved` });
      onSaved();
    } catch (e) { toast.push({ title: errorMessage(e) }); } finally { setBusy(false); }
  }
  return (
    <tr data-testid={`setting-${t.code}`}>
      <td>{t.name}<span className="block text-[11px] text-fg-tertiary">{t.generated ? "From records" : "Form"}</span></td>
      <td><DocRiskBadge risk={t.risk} />{t.risk === "LOW" && <span className="text-fg-tertiary text-[12px]">Low</span>}</td>
      <td>
        <Select value={level} onChange={(e) => setLevel(e.target.value as ApprovalLevel)} aria-label={`${t.name} approval`}>
          {(["NONE", "SINGLE", "REVIEW_AND_APPROVE"] as ApprovalLevel[]).map((l) => <option key={l} value={l} disabled={l === "NONE" && t.risk === "HIGH"}>{APPROVAL_TEXT[l]}</option>)}
        </Select>
      </td>
      <td>
        {schedulable ? (
          <div className="flex flex-wrap items-center gap-2 min-w-[220px]">
            <label className="inline-flex items-center gap-1 text-caption"><input type="checkbox" checked={auto} onChange={(e) => setAuto(e.target.checked)} aria-label={`${t.name} generate on schedule`} /> On</label>
            {freqs.length > 1
              ? <Select value={freq} disabled={!auto} onChange={(e) => setFreq(e.target.value as ScheduleFrequency)} aria-label={`${t.name} frequency`}>{freqs.map((f) => <option key={f} value={f}>{FREQ_TEXT[f]}</option>)}</Select>
              : <span className="text-caption text-fg-secondary">{FREQ_TEXT[freqs[0]]}</span>}
            {freq === "WEEKLY" && freqs.length > 1 && (
              <Select value={String(week)} disabled={!auto} onChange={(e) => setWeek(Number(e.target.value))} aria-label={`${t.name} week starts`}>
                {DAYS.map((d, i) => <option key={d} value={i}>Week starts {d}</option>)}
              </Select>
            )}
            {t.lineOption && (
              <Select value={scopeV} disabled={!auto || t.code === "production.line"} onChange={(e) => setScopeV(e.target.value as ScheduleScope)} aria-label={`${t.name} scope`}>
                {t.code !== "production.line" && <option value="FACTORY">Whole factory</option>}
                <option value="EACH_LINE">Each line</option>
              </Select>
            )}
          </div>
        ) : <span className="text-caption text-fg-tertiary">—</span>}
      </td>
      <td className="text-center"><input type="checkbox" checked={expected} disabled={t.period !== "DAY"} onChange={(e) => setExpected(e.target.checked)} aria-label="Expected daily" /></td>
      <td><Input className="w-20" inputMode="numeric" value={due} onChange={(e) => setDue(e.target.value)} aria-label="Decision hours" /></td>
      <td><Button size="sm" disabled={!dirty || busy} onClick={() => void save()}>Save</Button></td>
    </tr>
  );
}
