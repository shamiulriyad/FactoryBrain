using FactoryBrain.Application.Dtos.Qc;

namespace FactoryBrain.Application.Abstractions.Interfaces;

/// <summary>
/// Garment inspection workflow: submit an image, let the configured vision
/// provider analyse it (asynchronously), review and correct the predictions,
/// and report quality metrics from the persisted records.
/// </summary>
public interface IQcInspectionService
{
    Task<QcCreateResult> CreateAsync(QcCreateInspectionInput input, AuditActor actor, string? traceId, CancellationToken ct);
    Task<QcInspectionPage> ListAsync(QcInspectionQuery query, CancellationToken ct);
    Task<QcInspectionDetail?> GetAsync(Guid id, CancellationToken ct);
    /// <summary>The stored image; null when the inspection or its file is missing.</summary>
    Task<QcImageContent?> OpenImageAsync(Guid id, CancellationToken ct);
    Task<QcReviewResult> ReviewAsync(Guid id, QcReviewRequest request, AuditActor actor, string? traceId, CancellationToken ct);
    Task<QcRetryResult> RetryAsync(Guid id, AuditActor actor, string? traceId, CancellationToken ct);
    Task<QcSummaryResponse> SummaryAsync(QcSummaryQuery query, CancellationToken ct);
    QcVisionStatus VisionStatus();
}

public interface IQcDefectCategoryService
{
    Task<IReadOnlyList<QcCategoryDto>> ListAsync(bool includeInactive, CancellationToken ct);
    Task<QcCategoryWriteResult> CreateAsync(QcCategoryCreateRequest request, AuditActor actor, string? traceId, CancellationToken ct);
    Task<QcCategoryWriteResult> UpdateAsync(string code, QcCategoryUpdateRequest request, AuditActor actor, string? traceId, CancellationToken ct);
}

/// <summary>Claims and analyses queued inspections. Called by the background worker (and directly by tests).</summary>
public interface IQcInspectionProcessor
{
    /// <summary>Process at most one queued inspection. Returns false when nothing was waiting.</summary>
    Task<bool> ProcessNextAsync(CancellationToken ct);
}

/// <summary>Wakes the background worker when a new inspection is queued (a poll is the fallback).</summary>
public interface IQcWorkSignal
{
    void Notify();
    Task WaitAsync(TimeSpan timeout, CancellationToken ct);
}

public sealed record QcImageContent(Stream Content, string ContentType, long Length, string Sha256);

public enum QcCreateOutcome { Created, Replayed, Invalid, IdempotencyConflict }

public sealed record QcCreateResult(
    QcCreateOutcome Outcome,
    QcInspectionDetail? Inspection,
    IReadOnlyDictionary<string, string[]>? Errors = null);

public enum QcReviewOutcome { Ok, NotFound, InvalidState, VersionConflict, Invalid }

public sealed record QcReviewResult(
    QcReviewOutcome Outcome,
    QcInspectionDetail? Inspection = null,
    IReadOnlyDictionary<string, string[]>? Errors = null);

public enum QcRetryOutcome { Ok, NotFound, InvalidState, ProviderNotConfigured }

public sealed record QcRetryResult(QcRetryOutcome Outcome, QcInspectionDetail? Inspection = null);

public enum QcCategoryWriteOutcome { Ok, NotFound, Invalid, Duplicate, VersionConflict }

public sealed record QcCategoryWriteResult(
    QcCategoryWriteOutcome Outcome,
    QcCategoryDto? Category = null,
    IReadOnlyDictionary<string, string[]>? Errors = null);

// ── Image storage ───────────────────────────────────────────────────────────

/// <summary>
/// Stores inspection images outside the database. Keys are generated by the
/// store (never derived from client input) and validated on every read, so
/// a stored reference can't be turned into a path outside the store root.
/// </summary>
public interface IQcImageStore
{
    /// <summary>Persist <paramref name="content"/> and return its storage key.</summary>
    Task<string> SaveAsync(byte[] content, string extension, CancellationToken ct);
    /// <summary>Open a stored image; null when the key is invalid or the file is gone.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken ct);
    Task DeleteAsync(string key, CancellationToken ct);
}

// ── Computer-vision provider contract ───────────────────────────────────────

/// <summary>
/// A computer-vision backend that detects garment defects in one image.
/// Implementations must never invent results: on any failure they throw
/// <see cref="DefectDetectionException"/>. Output is normalised to
/// <see cref="DefectDetectionResult"/> so providers can be swapped without
/// touching the inspection workflow.
/// </summary>
public interface IDefectDetectionProvider
{
    /// <summary>Current configuration, without making a call. Never includes secrets.</summary>
    DefectProviderStatus Describe();
    Task<DefectDetectionResult> DetectAsync(DefectDetectionRequest request, CancellationToken ct);
}

public sealed record DefectProviderStatus(
    bool Configured,
    string Mode,
    string? Provider,
    string? Model,
    bool? LocalizationSupported,
    string? Reason);

public sealed record DetectionCategory(string Code, string Name, string? Description);

public sealed record DefectDetectionRequest(
    byte[] Image,
    string ContentType,
    int Width,
    int Height,
    IReadOnlyList<DetectionCategory> Categories,
    string ProductType,
    string Stage);

/// <summary>Axis-aligned box, normalised to [0,1]; origin top-left.</summary>
public sealed record NormalizedBox(double X, double Y, double Width, double Height);

public sealed record DetectedDefect(
    /// <summary>The provider's label (ideally one of the requested category codes).</summary>
    string Label,
    double? Confidence,
    NormalizedBox? Box,
    /// <summary>Flat [x1,y1,x2,y2,…] polygon, normalised; null when not supported.</summary>
    double[]? Polygon,
    string? Severity,
    string? Description);

public sealed record DefectDetectionResult(
    string Provider,
    string Model,
    string? ModelVersion,
    bool LocalizationSupported,
    IReadOnlyList<DetectedDefect> Defects);

/// <summary>
/// The provider could not produce a result. <see cref="Code"/> is stable
/// (<c>provider_not_configured</c>, <c>provider_timeout</c>,
/// <c>provider_unauthorized</c>, <c>provider_error</c>, <c>invalid_output</c>);
/// the message is safe to show and store (no keys, no response bodies).
/// </summary>
public sealed class DefectDetectionException : Exception
{
    public const string NotConfigured = "provider_not_configured";
    public const string Timeout       = "provider_timeout";
    public const string Unauthorized  = "provider_unauthorized";
    public const string ProviderError = "provider_error";
    public const string InvalidOutput = "invalid_output";

    public string Code { get; }

    public DefectDetectionException(string code, string message, Exception? inner = null) : base(message, inner)
    {
        Code = code;
    }
}
