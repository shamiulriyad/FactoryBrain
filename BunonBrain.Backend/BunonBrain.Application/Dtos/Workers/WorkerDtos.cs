/// <summary>
/// POST /api/workers/import. With <c>dryRun</c> (the default) nothing is
/// saved: the rows come back validated, for a preview. Without it the valid
/// rows are registered in one transaction and the invalid ones are skipped.
/// </summary>
public sealed record WorkerImportResultDto(
    bool DryRun,
    Guid FactoryId,
    int TotalRows, int ValidRows, int InvalidRows, int Imported,
    IReadOnlyList<string> Columns,
    IReadOnlyList<string> IgnoredColumns,
    IReadOnlyList<WorkerImportRowDto> Rows);

/// <summary>A generated CSV file.</summary>
public sealed record WorkerExport(string FileName, byte[] Content, int Rows);

/// <summary>A stored profile photograph.</summary>
public sealed record WorkerPhoto(Stream Content, string ContentType);
