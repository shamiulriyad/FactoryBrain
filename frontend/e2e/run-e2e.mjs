export const FAKE_LLM_FINDING = "E2E-LIVE-ANSWER: generated by the local fake model from the cited manuals.";
export const FORCE_LLM_FAILURE = "FORCE-LLM-FAILURE";
// QC vision: the API runs QC_VISION_PROVIDER=http against this harness. The
// detector below is a deterministic TEST model, named as such in every
// result; it exercises the real workflow, not any real model accuracy.
export const FAKE_QC_MODEL = "E2E-TEST-deterministic-detector";
const QC_DETECTOR_KEY = randomBytes(18).toString("base64url");
const PYRAG_COLLECTION = "e2e_kb";
const PYRAG_KEY = randomBytes(18).toString("base64url");

function startFakeLlm(mailbox) {
  // lastModel / lastKeySha256 let a test prove which settings Ask used,
  // without the harness ever echoing a key.
  const stats = { chat: 0, failures: 0, other: 0, lastModel: null, lastKeySha256: null };
  const server = http.createServer((req, res) => {
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", () => {
      if (req.method === "GET" && req.url === "/__stats") {
        res.setHeader("Content-Type", "application/json");
        return res.end(JSON.stringify(stats));
      }
      if (req.method === "GET" && req.url.startsWith("/__mail")) {
        // Test-only: emails the fake SMTP server received for ?to=…
        const to = new URL(req.url, "http://x").searchParams.get("to")?.toLowerCase();
        res.setHeader("Content-Type", "application/json");
        return res.end(JSON.stringify((mailbox?.messages ?? []).filter((m) => !to || m.to.includes(to)).map((m) => ({ to: m.to, body: m.body }))));
      }
      if (req.method === "POST" && req.url === "/v1/chat/completions") {
        stats.chat++;
        try { stats.lastModel = JSON.parse(body).model ?? null; } catch { stats.lastModel = null; }
        const bearer = String(req.headers.authorization ?? "").replace(/^Bearer /, "");
        stats.lastKeySha256 = bearer ? createHash("sha256").update(bearer).digest("hex") : null;
        if (body.includes(FORCE_LLM_FAILURE)) {
          stats.failures++;
          res.statusCode = 500;
          res.setHeader("Content-Type", "application/json");
          return res.end(JSON.stringify({ error: { type: "server_error", code: "e2e_forced" } }));
        }
        res.setHeader("Content-Type", "application/json");
        const content = JSON.stringify({ finding: FAKE_LLM_FINDING, findingBn: "E2E লাইভ উত্তর" });
        return res.end(JSON.stringify({ choices: [{ message: { role: "assistant", content } }] }));
      }
      // Fake Python RAG service (rag/main.py): agent runs and Ask query it.
      // Without it the API would default to http://127.0.0.1:8000, which can
      // be a developer's real RAG service (with a hosted model behind it).
      if (req.method === "GET" && req.url === "/health") {
        res.setHeader("Content-Type", "application/json");
        return res.end(JSON.stringify({ status: "ok", ready: true, qdrant: "healthy" }));
      }
      if (req.method === "POST" && req.url === `/api/kb/${PYRAG_COLLECTION}/query`) {
        stats.rag = (stats.rag ?? 0) + 1;
        res.setHeader("Content-Type", "application/json");
        if (req.headers["x-rag-api-key"] !== PYRAG_KEY) {
          res.statusCode = 401;
          return res.end(JSON.stringify({ detail: "invalid api key" }));
        }
        const question = (() => { try { return JSON.parse(body).question ?? ""; } catch { return ""; } })();
        if (question.includes("zzqx")) return res.end(JSON.stringify({ answer: "The documents do not cover this.", sources: [] }));
        return res.end(JSON.stringify({
          answer: "E2E-RAG-ANSWER: check the needle and bobbin, then re-thread (from the local fake RAG service).",
          sources: [{ document_id: "e2e-doc", chunk_id: "0", page: 1, source: "e2e-maintenance-manual.pdf", score: 0.8, excerpt: "Check the needle and bobbin before re-threading." }]
        }));
      }
      if (req.method === "POST" && req.url === "/__qc/detect") {
        stats.qcDetect = (stats.qcDetect ?? 0) + 1;
        res.setHeader("Content-Type", "application/json");
        if (req.headers.authorization !== `Bearer ${QC_DETECTOR_KEY}`) {
          res.statusCode = 401;
          return res.end(JSON.stringify({ error: "unauthorized" }));
        }
        return res.end(JSON.stringify({
          model: FAKE_QC_MODEL,
          modelVersion: "e2e-1",
          localization: true,
          defects: [
            { label: "skipped_stitch", confidence: 0.91, box: { x: 0.1, y: 0.15, width: 0.35, height: 0.2 }, severity: "major", description: "gap in the seam line" },
            { label: "stain", confidence: 0.72, box: { x: 0.55, y: 0.5, width: 0.2, height: 0.25 } },
            { label: "chalk_mark", confidence: 0.4 },
            { label: "hole", confidence: 0.05 }
          ]
        }));
      }
      stats.other++;
      res.statusCode = 404;
      res.end();
    });
  });
  return new Promise((resolve) => server.listen(0, "127.0.0.1", () => resolve({ server, stats, port: server.address().port })));
}

// ---------------------------------------------------------------------------
// Fake SMTP server: the API's real SMTP client delivers reset emails here, on
// 127.0.0.1. Messages are kept in memory for the tests; nothing is relayed.
// ---------------------------------------------------------------------------
function startFakeSmtp() {
  const messages = [];
  const server = createServer((socket) => {
    let buffer = "";
    let inData = false;
    let current = { to: [], data: "" };
    const reply = (line) => socket.write(line + "\r\n");
    reply("220 fake-smtp.e2e ready");
    socket.on("data", (chunk) => {
      buffer += chunk.toString("utf8");
      let idx;
      while (true) {
        if (inData) {
          idx = buffer.indexOf("\r\n.\r\n");
          if (idx === -1) return;
          current.data = buffer.slice(0, idx);
          buffer = buffer.slice(idx + 5);
          inData = false;
          messages.push({ to: current.to, raw: current.data, body: decodeBody(current.data) });
          current = { to: [], data: "" };
          reply("250 queued");
          continue;
        }
        idx = buffer.indexOf("\r\n");
        if (idx === -1) return;
        const line = buffer.slice(0, idx);
        buffer = buffer.slice(idx + 2);
        const cmd = line.slice(0, 4).toUpperCase();
        if (cmd === "EHLO" || cmd === "HELO") reply("250 fake-smtp.e2e");
        else if (cmd === "MAIL") reply("250 ok");
        else if (cmd === "RCPT") { current.to.push(line.replace(/^RCPT TO:\s*<?([^>]*)>?.*$/i, "$1").toLowerCase()); reply("250 ok"); }
        else if (cmd === "DATA") { inData = true; reply("354 end with <CRLF>.<CRLF>"); }
        else if (cmd === "QUIT") { reply("221 bye"); socket.end(); return; }
        else reply("250 ok");
      }
    });
    socket.on("error", () => {});
  });
  return new Promise((resolve) => server.listen(0, "127.0.0.1", () => resolve({ server, messages, port: server.address().port })));
}

/** Headers stripped, quoted-printable soft breaks and escapes undone, dot-stuffing removed. */
function decodeBody(raw) {
  const sep = raw.indexOf("\r\n\r\n");
  let body = sep === -1 ? raw : raw.slice(sep + 4);
  if (/content-transfer-encoding:\s*quoted-printable/i.test(raw.slice(0, sep))) {
    body = body.replace(/=\r\n/g, "").replace(/=([0-9A-F]{2})/gi, (_, h) => String.fromCharCode(parseInt(h, 16)));
  } else if (/content-transfer-encoding:\s*base64/i.test(raw.slice(0, sep))) {
    body = Buffer.from(body.replace(/\s+/g, ""), "base64").toString("utf8");
  }
  return body.replace(/^\.\./gm, ".");
}

