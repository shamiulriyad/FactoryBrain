/// <summary>
/// One section of the activity overview that a later module will fill
/// (attendance, shifts, …). <see cref="Available"/> is false and
/// <see cref="Items"/> is empty until that module exists: nothing is made up.
/// </summary>
public sealed record WorkerActivitySection(string Key, string Title, bool Available, string Note, IReadOnlyList<object> Items);

/// <summary>What the caller may do to this worker (the server enforces the same rules).</summary>
public sealed record WorkerCapabilities(
    bool Edit, bool ChangeStatus, bool AssignWorkstation, bool ManageAccount, bool ManageCards,
    IReadOnlyList<string> AllowedStatuses);

/// <summary>GET /api/workers/{id}/profile.</summary>
public sealed record WorkerProfileDto(
    WorkerDto Worker,
    FactoryRef Factory,
    // Always null for now: machines arrive with the machine-management module.
    string? Machine,
    WorkerAccountDto? Account,
    // Null when the caller may not see cards.
    IReadOnlyList<WorkerCardDto>? Cards,
    // Null when the caller may not see employment details.
    IReadOnlyList<WorkerStatusChangeDto>? StatusHistory,
    IReadOnlyList<WorkerActivitySection> Activity,
    WorkerCapabilities Can);

