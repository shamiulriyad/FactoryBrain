// ─── Section tabs ─────────────────────────────────────────────────────────

const SECTIONS: { href: string; label: string; perms: string[]; exact?: boolean }[] = [
  { href: MON, label: "Monitoring room", perms: [P.MonitoringView, P.DevicesView], exact: true },
  { href: `${MON}/cameras`, label: "Cameras", perms: [P.MonitoringView, P.CamerasView] },
  { href: `${MON}/activity`, label: "Activity", perms: [P.MonitoringView] },
  { href: `${MON}/events`, label: "Event timeline", perms: [P.MonitoringView, P.DevicesView] },
  { href: `${MON}/alerts`, label: "Alerts", perms: [P.MonitoringView, P.DevicesView] },
  { href: `${MON}/devices`, label: "Device health", perms: [P.DevicesView] },
  { href: `${MON}/simulator`, label: "Simulator", perms: [P.MonitoringSimulate] }
];

function SectionLink({ s, active }: { s: (typeof SECTIONS)[number]; active: boolean }) {
  const allowed = useCan(...s.perms);
  if (!allowed) return null;
  return (
    <Link href={s.href} aria-current={active ? "page" : undefined}
      className={cn("px-3 h-9 inline-flex items-center whitespace-nowrap text-caption border-b-2 -mb-px",
        active ? "border-[var(--accent)] text-fg-primary font-medium" : "border-transparent text-fg-secondary hover:text-fg-primary")}>
      {s.label}
    </Link>
  );
}

export function MonitoringTabs({ className }: { className?: string }) {
  const pathname = usePathname() ?? "";
  return (
    <nav aria-label="Monitoring sections" className={cn("flex items-center gap-1 border-b border-border-subtle overflow-x-auto", className)} data-testid="monitoring-tabs">
      {SECTIONS.map((s) => (
        <SectionLink key={s.href} s={s} active={s.exact ? pathname === s.href : pathname === s.href || pathname.startsWith(s.href + "/")} />
      ))}
    </nav>
  );
}

// ─── Labels ───────────────────────────────────────────────────────────────

/** SIMULATED (amber, flask) or REAL. Always shown on events and alerts. */
export function SourceBadge({ source, className }: { source: string; className?: string }) {
  if (source === "SIMULATED")
    return (
      <span className={cn("inline-flex items-center gap-1 h-5 px-1.5 rounded-sm border border-[var(--risk-medium)] text-[var(--risk-medium)] text-[10px] font-semibold tracking-wide shrink-0", className)}
        title="Generated by the monitoring simulator: not real camera AI or real equipment" data-testid="source-simulated">
        <FlaskConical size={10} aria-hidden /> SIMULATED
      </span>
    );
  return (
    <span className={cn("inline-flex items-center gap-1 h-5 px-1.5 rounded-sm border border-border-strong text-fg-secondary text-[10px] font-semibold tracking-wide shrink-0", className)}
      title="From real equipment or a real producer" data-testid="source-real">
      <Radio size={10} aria-hidden /> REAL
    </span>
  );
}

export function SeverityBadge({ severity }: { severity: string }) {
  return <Badge tone={SEVERITY_TONE[severity] ?? "neutral"} dot>{severity}</Badge>;
}

export function AlertStatusBadge({ status }: { status: string }) {
  return <Badge tone={ALERT_STATUS_TONE[status] ?? "neutral"} testId={`alert-status-${status}`}>{ALERT_STATUS_LABEL[status] ?? status}</Badge>;
}

export function ConnectionBadge({ status, label, simulated }: { status: string; label?: string; simulated?: boolean }) {
  const text = status === "ONLINE" ? "Online" : status === "OFFLINE" ? "Offline" : status === "INACTIVE" ? "Deactivated" : status === "MAINTENANCE" ? "Maintenance" : "Unknown";
  return (
    <span className="inline-flex items-center gap-1.5">
      <Badge tone={CONNECTION_TONE[status] ?? "neutral"} dot><span title={label}>{text}</span></Badge>
      {simulated && <SourceBadge source="SIMULATED" />}
    </span>
  );
}

const SEVERITY_DOT: Record<string, string> = {
  CRITICAL: "bg-[var(--risk-high)]",
  WARNING: "bg-[var(--risk-medium)]",
  INFO: "bg-[var(--fg-tertiary,#94a3b8)]"
};

function EventIcon({ type }: { type: string }) {
  const cls = "text-fg-tertiary shrink-0";
  switch (type) {
    case "CAMERA_STATUS_CHANGED": return <Cctv size={14} className={cls} aria-hidden />;
    case "DEVICE_STATUS_CHANGED": return <Cpu size={14} className={cls} aria-hidden />;
    case "MODEL_STATUS_CHANGED": return <Box size={14} className={cls} aria-hidden />;
    case "UNCERTAIN_DETECTION": return <AlertTriangle size={14} className="text-[var(--risk-medium)] shrink-0" aria-hidden />;
    case "ACTIVITY_CLASSIFIED":
    case "ACTIVITY_STATE_CHANGED": return <PersonStanding size={14} className={cls} aria-hidden />;
    case "ACTIVITY_UNCERTAIN":
    case "GARMENT_ACTIVITY_UNCERTAIN": return <HelpCircle size={14} className="text-fg-tertiary shrink-0" aria-hidden />;
    case "GARMENT_ACTIVITY_CLASSIFIED":
    case "GARMENT_ACTIVITY_CHANGED": return <Scissors size={14} className={cls} aria-hidden />;
    case "ZONE_ENTERED":
    case "ZONE_EXITED": return <ScanLine size={14} className={cls} aria-hidden />;
    default: return <CircleDot size={14} className={cls} aria-hidden />;
  }
}

// ─── Live indicator ───────────────────────────────────────────────────────

const LIVE_TEXT: Record<LiveState, string> = {
  connecting: "Connecting…",
  live: "Live",
  reconnecting: "Reconnecting…",
  offline: "Offline: retrying",
  denied: "Live updates not allowed",
  off: "Live updates off"
};

export function LiveIndicator({ state, lastMessageAt, className }: { state: LiveState; lastMessageAt?: Date | null; className?: string }) {
  const tone = state === "live" ? "text-[var(--risk-low,#16a34a)]" : state === "reconnecting" || state === "connecting" ? "text-[var(--risk-medium)]" : "text-fg-tertiary";
  return (
    <span className={cn("inline-flex items-center gap-1.5 text-caption", tone, className)} role="status" aria-live="polite" data-testid="live-indicator" data-state={state}>
      {state === "live" ? (
        <span className="relative flex h-2.5 w-2.5" aria-hidden>
          <span className="absolute inline-flex h-full w-full rounded-full bg-current opacity-50 motion-safe:animate-ping" />
          <span className="relative inline-flex h-2.5 w-2.5 rounded-full bg-current" />
        </span>
      ) : state === "offline" || state === "denied" ? <WifiOff size={13} aria-hidden /> : <Signal size={13} aria-hidden />}
      {LIVE_TEXT[state]}
      {state === "live" && lastMessageAt && <span className="text-fg-tertiary">· last update {dhakaTime(lastMessageAt.toISOString())}</span>}
    </span>
  );
}

// ─── Events ───────────────────────────────────────────────────────────────

export function eventWhere(e: MonitoringEvent): string {
  return [e.factoryCode, e.line?.name, e.camera?.code ?? e.device?.code, e.zone ? `zone ${e.zone.name}` : null].filter(Boolean).join(" · ");
}

/** A compact, scannable list of events (newest first). */
export function EventList({ rows, onOpen, highlight, empty, testId, dense, activityByTrack }: {
  rows: MonitoringEvent[];
  onOpen?: (e: MonitoringEvent) => void;
  highlight?: Set<string>;
  empty?: ReactNode;
  testId?: string;
  dense?: boolean;
  /** Latest predicted activity per temporary track id, shown beside the track on its other events. */
  activityByTrack?: Map<string, { activity: string; confidence?: number | null }>;
}) {
  if (rows.length === 0) return <>{empty ?? <p className="px-4 py-6 text-caption text-fg-tertiary">No events yet.</p>}</>;
  return (
    <ul className="divide-y divide-border-subtle" data-testid={testId}>
      {rows.map((e) => {
        const status = payloadString(e, "toStatus");
        const body = (
          <>
            <span className={cn("mt-1.5 h-2 w-2 rounded-full shrink-0", SEVERITY_DOT[e.severity])} aria-hidden />
            <div className="min-w-0 flex-1">
              <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
                <EventIcon type={e.eventType} />
                <span className="text-body font-medium text-fg-primary">{EVENT_TYPE_LABEL[e.eventType] ?? e.eventType}</span>
                {status && <Badge tone={status === "OFFLINE" || status === "ERROR" ? "danger" : status === "ONLINE" || status === "READY" ? "success" : "neutral"}>{status}</Badge>}
                {isActivityEvent(e.eventType) && payloadString(e, "activity") && (
                  <ActivityBadge activity={payloadString(e, "activity")!} previous={payloadString(e, "previousActivity")} reason={payloadString(e, "reason")}
                    garment={isGarmentEvent(e.eventType)} />
                )}
                <SourceBadge source={e.sourceType} />
                {e.trackId && <span className="font-mono text-caption text-fg-secondary" title="Temporary camera-local track number: not a worker identity">track {e.trackId}</span>}
                {e.trackId && !isActivityEvent(e.eventType) && activityByTrack?.get(e.trackId) && (
                  <ActivityBadge activity={activityByTrack.get(e.trackId)!.activity} confidence={activityByTrack.get(e.trackId)!.confidence} />
                )}
                {e.verifiedWorker && <Badge tone="accent" title="Identity verified by RFID card">{e.verifiedWorker.code}</Badge>}
                {e.confidence != null && <span className="text-caption text-fg-tertiary">conf {e.confidence.toFixed(2)}</span>}
              </div>
              {!dense && <p className="text-caption text-fg-secondary truncate">{eventWhere(e)}</p>}
            </div>
            <time className="text-caption text-fg-tertiary tabular-nums whitespace-nowrap" dateTime={e.occurredAt} title={dhaka(e.occurredAt) + " (Dhaka)"}>{dhakaTime(e.occurredAt)}</time>
          </>
        );
        const cls = cn("flex items-start gap-3 px-4 py-2.5 w-full text-left", highlight?.has(e.id) && "bg-[var(--accent-soft)] transition-colors duration-1000");
        return (
          <li key={e.id} data-testid="event-row" data-source={e.sourceType}>
            {onOpen ? <button type="button" className={cn(cls, "hover:bg-surface-2")} onClick={() => onOpen(e)}>{body}</button> : <div className={cls}>{body}</div>}
          </li>
        );
      })}
    </ul>
  );
}

